// Ported from the classic client's client/src/utils/swatch/index.ts (#415 step 3).
// 3D-printable filament swatch generation. The swatch is a small card meant to
// be printed in the filament itself, carrying the same info as the printed
// labels (vendor, name, material, temperatures, id) plus a Spoolman QR code.
// The text/QR form a raised one-layer marking whose triangles are face-colored
// black or white — whichever contrasts best with the filament color — so it
// can be printed with a filament change at the last layer, or mapped to a
// second filament by slicers that import 3MF face colors (e.g. Bambu Studio).
//
// Adapted for client_v2: the classic client's `swatchInputFromFilament` took a
// React `IFilament`; this version takes client_v2's `Filament` view model
// ($lib/types) instead. See swatchInputFromFilament below for the field
// mapping and its deviations from the classic version (missing/zero
// temperatures, color hex format).

